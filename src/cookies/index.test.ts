// THE regression. `--cookies-from-browser P --cookies OUT` writes OUT *after* the HTTP request, so
// OUT always holds YouTube's ANONYMOUS cookies even when P is empty: countCookieLines(staged) was
// 8, the `=== 0` guard never tripped once, and an Import from a not-signed-in profile REPLACED a
// working authenticated jar with an anonymous one. probe() then passed too (PROBE_VIDEO_ID is
// public and needs no auth), so the console reported "imported and working" for the one operation
// that had just destroyed the session it was meant to install.
describe("CookieService.importFromBrowser: an anonymous jar is not a session", () => {
  it("REJECTS it, and the working jar on disk is byte-identical afterwards", async () => {
    const profile = await profileWithDb();
    const cacheDir = await tmp();
    const jarPath = defaultJarPath(cacheDir);
    // The thing the old guard destroyed: a jar that WORKS is already installed.
    await mkdir(cacheDir, { recursive: true });
    await writeFile(jarPath, NETSCAPE_EXPORT, { mode: 0o600 });
    const before = await readFile(jarPath, "utf8");
    const { run, seen } = runWriting(ANONYMOUS_JAR, {
      stdout: "Extracted 0 cookies from chromium\n",
    });
    const { svc, applyCookies, resolve } = await make({
      cacheDir,
      jarPath,
      browserProfile: profile,
      run,
    });

    expect(await svc.importFromBrowser()).toEqual({ ok: false, reason: NOT_SIGNED_IN });

    // Byte for byte: the session the operator already had survives the pointless import.
    expect(await readFile(jarPath, "utf8")).toBe(before);
    expect(await mode(jarPath)).toBe("600");
    // Nothing was hot-applied and no probe was spent — the failure is total and quiet.
    expect(applyCookies).not.toHaveBeenCalled();
    expect(resolve).not.toHaveBeenCalled();
    // The staged file is discarded, not left in CACHE_DIR holding response cookies forever.
    expect(existsSync(seen.staged)).toBe(false);
    // And the console does not claim a browser session it does not have.
    expect(svc.health().source).toBe("env");
  });

  it("REJECTS it on CONTENT alone when yt-dlp prints no count at all", async () => {
    // Older yt-dlp, no `Extracted N` line: gate (a) has nothing to say and gate (c) does the work.
    const { run } = runWriting(ANONYMOUS_JAR);
    const { svc, applyCookies, resolve } = await make({
      browserProfile: await profileWithDb(),
      run,
    });

    expect(await svc.importFromBrowser()).toEqual({ ok: false, reason: NOT_SIGNED_IN });
    expect(applyCookies).not.toHaveBeenCalled();
    expect(resolve).not.toHaveBeenCalled();
  });

  it("accepts a staged jar carrying __Secure-1PSID and promotes it over the live one", async () => {
    const profile = await profileWithDb();
    const cacheDir = await tmp();
    const jarPath = defaultJarPath(cacheDir);
    await mkdir(cacheDir, { recursive: true });
    await writeFile(jarPath, "# stale\n");
    const { run, seen } = runWriting(SIGNED_IN_JAR);
    const { svc, applyCookies, resolve } = await make({
      cacheDir,
      jarPath,
      browserProfile: profile,
      run,
    });

    expect(await svc.importFromBrowser()).toEqual({ ok: true, reason: null });

    // Promoted whole, owner-only, staging cleaned up, hot-applied, then proven.
    expect(await readFile(jarPath, "utf8")).toBe(SIGNED_IN_JAR);
    expect(await mode(jarPath)).toBe("600");
    expect(existsSync(seen.staged)).toBe(false);
    expect(applyCookies).toHaveBeenCalledWith(jarPath);
    expect(resolve).toHaveBeenCalledWith(PROBE_VIDEO_ID);
    expect(svc.health()).toMatchObject({ configured: true, source: "browser" });
  });

  it("does not count an auth cookie whose value is EMPTY as a sign-in", async () => {
    const profile = await profileWithDb();
    const cacheDir = await tmp();
    const jarPath = defaultJarPath(cacheDir);
    await mkdir(cacheDir, { recursive: true });
    await writeFile(jarPath, NETSCAPE_EXPORT, { mode: 0o600 });
    // yt-dlp says it read 41 cookies and the file is full of well-formed lines — but the one that
    // matters decrypted to nothing, which is a wrong key, not a session.
    const { run } = runWriting(EMPTY_AUTH_JAR, { stdout: "Extracted 41 cookies from chromium\n" });
    const { svc, applyCookies } = await make({ cacheDir, jarPath, browserProfile: profile, run });

    expect(await svc.importFromBrowser()).toEqual({ ok: false, reason: NOT_SIGNED_IN });
    expect(await readFile(jarPath, "utf8")).toBe(NETSCAPE_EXPORT);
    expect(applyCookies).not.toHaveBeenCalled();
  });

  it("warns about undecryptable cookies on an otherwise good import, echoing no stderr", async () => {
    const profile = await profileWithDb();
    const cacheDir = await tmp();
    const jarPath = defaultJarPath(cacheDir);
    const { run } = runWriting(SIGNED_IN_JAR, {
      stdout: "Extracted 12 cookies from chromium\n",
      stderr: `WARNING: 3 cookies could not be decrypted (SID=${SECRET})`,
    });
    const { svc, applyCookies } = await make({ cacheDir, jarPath, browserProfile: profile, run });

    const res = await svc.importFromBrowser();

    // The import SUCCEEDED — an auth cookie did survive and is installed — and the operator still
    // hears that the sidecar is dropping cookies, because that is a keyring, not a fluke.
    expect(res).toEqual({ ok: true, reason: null, warning: UNDECRYPTABLE });
    expect(JSON.stringify(res)).not.toContain(SECRET);
    expect(applyCookies).toHaveBeenCalledWith(jarPath);
  });
});

// health() runs on every page load and the Import button hangs off it, so the profile probe has to
// be cheap AND right. Three states, because the two failures have different fixes: nothing usable
// at that path (sidecar down, volume unmounted, PUID mismatch) versus a directory that reads fine
// and holds no cookie DB (COOKIE_BROWSER_PROFILE aimed at $HOME instead of the user-data-dir),
// which used to surface as a baffling yt-dlp failure halfway through an import.
describe("the sidecar profile probe has three states", () => {
  it('finds the DB at <p>/Default/Network/Cookies — "ok"', async () => {
    const { svc } = await make({ browserProfile: await profileWithDb() });
    expect(svc.health().browserProfileAvailable).toBe(true);
  });

  it('finds the DB under a second identity, <p>/Profile 1/Cookies — "ok"', async () => {
    const { svc } = await make({ browserProfile: await profileWithDb("Profile 1/Cookies") });
    expect(svc.health().browserProfileAvailable).toBe(true);
  });

  it('a readable directory with no cookie DB is "no-db", and says so without spawning', async () => {
    const { svc, run } = await make({ browserProfile: await tmp("jukebox-profile-") });

    expect(svc.health().browserProfileAvailable).toBe(false);
    expect(await svc.importFromBrowser()).toEqual({ ok: false, reason: NO_COOKIE_DB });
    expect(run).not.toHaveBeenCalled();
  });

  it('a path that is not there at all is "missing" — the sidecar-is-down reason', async () => {
    const { svc, run } = await make({ browserProfile: join(await tmp(), "never-mounted") });

    expect(svc.health().browserProfileAvailable).toBe(false);
    expect(await svc.importFromBrowser()).toEqual({
      ok: false,
      reason: "the browser profile is not readable (is the sidecar up?)",
    });
    expect(run).not.toHaveBeenCalled();
  });

  it("probes a BOUNDED set of paths — it never walks the profile looking for a DB", async () => {
    // A `Cookies` file that is NOT in one of the places chromium puts one. Walking the tree would
    // find it; the bounded probe must not, because this runs on every page load against a volume
    // a browser keeps tens of thousands of cache files in.
    const { svc } = await make({ browserProfile: await profileWithDb("Default/Cache/Cookies") });
    expect(svc.health().browserProfileAvailable).toBe(false);
  });
});
