const dirs: string[] = [];
afterEach(async () => {
  await Promise.all(dirs.splice(0).map((d) => rm(d, { recursive: true, force: true })));
});

async function tmp(prefix = "ytbot-cookies-"): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), prefix));
  dirs.push(dir);
  return dir;
}

function okRun(over: Partial<YtDlpRun> = {}): YtDlpRun {
  return { stdout: "", stderr: "", code: 0, ...over };
}

async function make(over: Partial<CookieServiceDeps> = {}) {
  const cacheDir = await tmp();
  const jarPath = defaultJarPath(cacheDir);
  const resolve = vi.fn(async (_id: string): Promise<TrackMeta> => meta);
  const applyCookies = vi.fn<(path: string | null) => void>();
  const run = vi.fn(async (_args: string[], _timeoutMs: number): Promise<YtDlpRun> => okRun());
  const svc = new CookieService({
    cacheDir,
    jarPath,
    youtube: { resolve },
    browserProfile: null,
    applyCookies,
    run,
    now: () => 1_700_000_000_000,
    ...over,
  });
  return { svc, cacheDir, jarPath, resolve, applyCookies, run };
}

/** File permission bits, as an octal string — the jar must be 0600 and nothing looser. */
async function mode(path: string): Promise<string> {
  return ((await stat(path)).mode & 0o777).toString(8);
}

