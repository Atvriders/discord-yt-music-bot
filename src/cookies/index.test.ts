describe("CookieService.saveFromText", () => {
  it("accepts a Netscape cookies.txt export: writes the jar 0600 and hot-applies it", async () => {
    const { svc, jarPath, applyCookies, resolve } = await make();

    const res = await svc.saveFromText(NETSCAPE_EXPORT);

    expect(res).toEqual({ ok: true, reason: null });
    // The export is kept as-is (both cookie lines survive, HttpOnly prefix included).
    const jar = await readFile(jarPath, "utf8");
    expect(countCookieLines(jar)).toBe(2);
    expect(jar).toContain("#HttpOnly_.youtube.com");
    // A logged-in Google session on a shared volume: owner-only, always.
    expect(await mode(jarPath)).toBe("600");
    // Hot-applied — the NEXT yt-dlp run uses it, with no restart.
    expect(applyCookies).toHaveBeenCalledWith(jarPath);
    // …and proven with a real extraction rather than reported as "saved" on faith.
    expect(resolve).toHaveBeenCalledWith(PROBE_VIDEO_ID);
  });

  it('accepts a one-line "Cookie: a=b; c=d" header: converts, writes 0600 and hot-applies', async () => {
    const { svc, jarPath, applyCookies } = await make();

    const res = await svc.saveFromText(HEADER_PASTE);

    expect(res).toEqual({ ok: true, reason: null });
    const jar = await readFile(jarPath, "utf8");
    expect(jar.startsWith("# Netscape HTTP Cookie File")).toBe(true);
    // Three name=value pairs became three tab-separated cookie lines.
    expect(countCookieLines(jar)).toBe(3);
    expect(jar).toContain(`\tSID\t${SECRET}`);
    expect(await mode(jarPath)).toBe("600");
    expect(applyCookies).toHaveBeenCalledWith(jarPath);
  });

  it("writes 0600 even when a looser jar already exists (tmp + rename, not a truncate)", async () => {
    const { svc, cacheDir, jarPath, applyCookies } = await make();
    await mkdir(cacheDir, { recursive: true });
    await writeFile(jarPath, "# stale\n");
    await chmod(jarPath, 0o644);

    expect(await svc.saveFromText(HEADER_PASTE)).toEqual({ ok: true, reason: null });

    expect(await mode(jarPath)).toBe("600");
    expect(await readFile(jarPath, "utf8")).not.toContain("# stale");
    expect(applyCookies).toHaveBeenCalledWith(jarPath);
  });

  it("reports source/updatedAt through health() once it has written a jar", async () => {
    const { svc } = await make({ now: () => 1234 });

    expect(svc.health()).toEqual({
      configured: false,
      source: "none",
      updatedAt: null,
      lastCheck: null,
      browserProfileAvailable: false,
    });

    await svc.saveFromText(HEADER_PASTE);

    expect(svc.health()).toEqual({
      configured: true,
      source: "paste",
      updatedAt: 1234,
      lastCheck: { at: 1234, ok: true, reason: null },
      browserProfileAvailable: false,
    });
  });

  it("REJECTS junk that yields no cookies — and quotes none of it back", async () => {
    const { svc, jarPath, applyCookies, resolve } = await make();
    // No "=" anywhere, so the header parser finds no name/value pair: the "I pasted the wrong
    // thing" case. The junk carries SECRET so an echo of the input is unmissable.
    const junk = `zorblat ${SECRET} quibnar`;

    const res = await svc.saveFromText(junk);

    expect(res.ok).toBe(false);
    expect(res.reason).toBe("no cookies found in that text");
    // The reason is a literal WE wrote: not one byte of the paste, not even a length or a prefix.
    // Checked word by word, so a future "reason" that helpfully quotes the input fails here.
    for (const word of junk.split(/\s+/)) expect(res.reason).not.toContain(word);
    // A rejected paste changes nothing: no jar on disk, nothing hot-applied, no probe spent.
    await expect(stat(jarPath)).rejects.toMatchObject({ code: "ENOENT" });
    expect(applyCookies).not.toHaveBeenCalled();
    expect(resolve).not.toHaveBeenCalled();
    expect(svc.health().configured).toBe(false);
  });

  it("rejects an empty / whitespace-only box the same way", async () => {
    const { svc, applyCookies } = await make();
    for (const junk of ["", "   \n\t\n ", "# Netscape HTTP Cookie File\n"]) {
      const res = await svc.saveFromText(junk);
      expect(res).toEqual({ ok: false, reason: "no cookies found in that text" });
    }
    expect(applyCookies).not.toHaveBeenCalled();
  });

  it("returns the PROBE's verdict, so a saved-but-still-blocked jar never reads as working", async () => {
    const resolve = vi.fn(async (): Promise<TrackMeta> => {
      throw new YtError(YtErrorKind.IpBlocked, "Sign in to confirm you're not a bot");
    });
    const { svc, jarPath, applyCookies } = await make({ youtube: { resolve } });

    const res = await svc.saveFromText(HEADER_PASTE);

    expect(res).toEqual({ ok: false, reason: "sign-in / bot check" });
    // The jar WAS written and applied — the operator's paste is not thrown away because
    // YouTube is still unhappy; only the verdict is negative.
    expect(await mode(jarPath)).toBe("600");
    expect(applyCookies).toHaveBeenCalledWith(jarPath);
    expect(svc.health().lastCheck).toEqual({
      at: 1_700_000_000_000,
      ok: false,
      reason: "sign-in / bot check",
    });
  });

  it("reports an unwritable CACHE_DIR without applying anything", async () => {
    // A path whose parent is a FILE: mkdir -p and writeFile both fail, like a full disk would.
    const cacheDir = await tmp();
    const notADir = join(cacheDir, "wall");
    await writeFile(notADir, "");
    const { svc, applyCookies, resolve } = await make({
      cacheDir: join(notADir, "cache"),
      jarPath: join(notADir, "cache", COOKIE_JAR_FILE),
    });

    const res = await svc.saveFromText(HEADER_PASTE);

    expect(res.ok).toBe(false);
    expect(res.reason).toBe("could not write the cookie jar (disk full or CACHE_DIR unwritable?)");
    expect(res.reason).not.toContain(SECRET);
    expect(applyCookies).not.toHaveBeenCalled();
    expect(resolve).not.toHaveBeenCalled();
  });

  it("SAVES a consent-only paste, and warns that it carries no sign-in cookie", async () => {
    const { svc, jarPath, applyCookies } = await make();
    // Exactly what `document.cookie` yields: the auth cookies are HttpOnly, so they are simply not
    // in that string. The paste is legitimate (a consent jar clears the EU interstitial) and the
    // probe passes on an unflagged IP — but "it worked" would send the operator off believing they
    // had installed a session.
    const res = await svc.saveFromText("Cookie: PREF=tz=Etc.UTC; SOCS=CAI; YSC=abc");

    expect(res).toEqual({ ok: true, reason: null, warning: NO_AUTH_PASTE });
    // Saved and applied, not rejected — the warning rides ALONGSIDE the success.
    expect(countCookieLines(await readFile(jarPath, "utf8"))).toBe(3);
    expect(applyCookies).toHaveBeenCalledWith(jarPath);
  });

  it("attaches no warning at all when the paste really does carry a sign-in cookie", async () => {
    const { svc } = await make();
    expect((await svc.saveFromText(NETSCAPE_EXPORT)).warning).toBeUndefined();
    expect((await svc.saveFromText(HEADER_PASTE)).warning).toBeUndefined();
  });
});

