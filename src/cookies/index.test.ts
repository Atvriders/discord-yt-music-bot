/**
 * A chromium profile directory as yt-dlp expects to find one: a cookie DB where the network
 * service actually puts it. The profile probe now refuses a directory with no DB under it, so
 * every import test needs a real one — a bare tmp dir is the "COOKIE_BROWSER_PROFILE is aimed one
 * level off the user-data-dir" case, not a healthy sidecar.
 */
async function profileWithDb(rel = "Default/Network/Cookies"): Promise<string> {
  const dir = await tmp("jukebox-profile-");
  const db = join(dir, rel);
  await mkdir(dirname(db), { recursive: true });
  await writeFile(db, "SQLite format 3\u0000");
  return dir;
}

/**
 * A yt-dlp stand-in that writes `jar` to whatever `--cookies` names — i.e. to the STAGED file,
 * exactly as the real thing does — and remembers the path so a test can prove it was cleaned up.
 */
function runWriting(jar: string, over: Partial<YtDlpRun> = {}) {
  const seen: { staged: string } = { staged: "" };
  const run = vi.fn(async (args: string[]): Promise<YtDlpRun> => {
    seen.staged = args[args.indexOf("--cookies") + 1] ?? "";
    await writeFile(seen.staged, jar);
    return okRun(over);
  });
  return { run, seen };
}

