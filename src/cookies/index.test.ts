describe("CookieService.importFromBrowser", () => {
  it("with NO profile configured: a clear ok:false, and nothing is spawned", async () => {
    const { svc, run, applyCookies, resolve } = await make({ browserProfile: null });

    const res = await svc.importFromBrowser();

    expect(res).toEqual({
      ok: false,
      reason: "no browser profile configured (set COOKIE_BROWSER_PROFILE)",
    });
    // The whole point: no yt-dlp, no probe, no state change when the sidecar isn't deployed.
    expect(run).not.toHaveBeenCalled();
    expect(applyCookies).not.toHaveBeenCalled();
    expect(resolve).not.toHaveBeenCalled();
    expect(svc.health().browserProfileAvailable).toBe(false);
  });

  it("with a profile configured: invokes yt-dlp with --cookies-from-browser AND --cookies", async () => {
    const profile = await profileWithDb();
    const cacheDir = await tmp();
    const jarPath = defaultJarPath(cacheDir);
    // yt-dlp given both flags SAVES the resulting jar to whatever --cookies names. We import into
    // a STAGED file, never the live jar: yt-dlp LOADS --cookies too and saves the MERGE, so writing
    // straight into the live jar means the stale cookies we are replacing survive the import.
    let sawCookiesArg: string | undefined;
    const run = vi.fn(async (args: string[]): Promise<YtDlpRun> => {
      sawCookiesArg = args[args.indexOf("--cookies") + 1];
      await writeFile(sawCookiesArg!, NETSCAPE_EXPORT, { mode: 0o644 });
      return okRun();
    });
    const { svc, applyCookies, resolve } = await make({
      cacheDir,
      jarPath,
      browserProfile: profile,
      run,
      ytdlpTimeoutMs: 12_345,
    });

    const res = await svc.importFromBrowser();

    expect(res).toEqual({ ok: true, reason: null });
    expect(run).toHaveBeenCalledOnce();
    const [args, timeoutMs] = run.mock.calls[0] as unknown as [string[], number];
    // The pairing IS the feature: read the live profile, write the merged jar to OUR file.
    expect(args).toContain("--cookies-from-browser");
    expect(args[args.indexOf("--cookies-from-browser") + 1]).toBe(`chromium:${profile}`);
    expect(args).toContain("--cookies");
    // Staged NEXT TO the jar, not the jar itself — so a refresh genuinely replaces stale cookies
    // and a failed import cannot damage a jar that currently works.
    expect(sawCookiesArg).not.toBe(jarPath);
    expect(sawCookiesArg!.startsWith(`${jarPath}.import.`)).toBe(true);
    // …and the staged jar is PROMOTED over the live one on success, with the staging file cleaned up.
    expect(await readFile(jarPath, "utf8")).toBe(NETSCAPE_EXPORT);
    expect(existsSync(sawCookiesArg!)).toBe(false);
    // Metadata only — never pull the audio just to harvest cookies.
    expect(args).toContain("--skip-download");
    expect(args).toContain("--simulate");
    // …but NOT --no-warnings, which every other yt-dlp call in the bot passes. A cookie yt-dlp
    // cannot decrypt is reported as a WARNING and then dropped silently, and that warning is the
    // only way the success path can tell the operator their sidecar grew a keyring.
    expect(args).not.toContain("--no-warnings");
    expect(args[args.length - 1]).toBe(`https://www.youtube.com/watch?v=${PROBE_VIDEO_ID}`);
    expect(timeoutMs).toBe(12_345);
    // Imported jars get the same treatment as pasted ones: 0600, hot-applied, then proven.
    expect(await mode(jarPath)).toBe("600");
    expect(applyCookies).toHaveBeenCalledWith(jarPath);
    expect(resolve).toHaveBeenCalledWith(PROBE_VIDEO_ID);
    expect(svc.health()).toMatchObject({
      configured: true,
      source: "browser",
      browserProfileAvailable: true,
    });
  });

  it("refuses a profile path yt-dlp would parse as a keyring/container, without spawning", async () => {
    for (const profile of ["/browser/profile:1", "/browser+gnomekeyring"]) {
      const { svc, run } = await make({ browserProfile: profile });
      expect(await svc.importFromBrowser()).toEqual({
        ok: false,
        reason: "the browser profile path may not contain ':' or '+'",
      });
      expect(run).not.toHaveBeenCalled();
    }
  });

  it("says the sidecar is down when the profile dir is absent, without spawning", async () => {
    const { svc, run } = await make({ browserProfile: join(await tmp(), "never-mounted") });

    expect(await svc.importFromBrowser()).toEqual({
      ok: false,
      reason: "the browser profile is not readable (is the sidecar up?)",
    });
    expect(run).not.toHaveBeenCalled();
    expect(svc.health().browserProfileAvailable).toBe(false);
  });

  it("reports an EMPTY profile when yt-dlp exits clean with no cookie lines staged", async () => {
    const profile = await profileWithDb();
    const cacheDir = await tmp();
    const jarPath = defaultJarPath(cacheDir);
    // A header and nothing under it. yt-dlp ran and had nothing to write, which is a plumbing
    // problem (the wrong directory) and a different fix from "go and sign in".
    const { run } = runWriting("# Netscape HTTP Cookie File\n");
    const { svc, applyCookies } = await make({ cacheDir, jarPath, browserProfile: profile, run });

    expect(await svc.importFromBrowser()).toEqual({ ok: false, reason: PROFILE_EMPTY });
    expect(applyCookies).not.toHaveBeenCalled();
  });

  it("reports an EMPTY profile when yt-dlp exits clean without staging a file at all", async () => {
    const profile = await profileWithDb();
    const { svc, applyCookies } = await make({
      browserProfile: profile,
      run: vi.fn(async (): Promise<YtDlpRun> => okRun()),
    });

    expect(await svc.importFromBrowser()).toEqual({ ok: false, reason: PROFILE_EMPTY });
    expect(applyCookies).not.toHaveBeenCalled();
  });

  it("translates a non-zero exit into a fixed reason and never echoes stderr", async () => {
    const profile = await profileWithDb();
    const cases: ReadonlyArray<[string, string]> = [
      [
        `could not find chromium cookies database in ${SECRET}`,
        "no chromium profile at that path — check the sidecar's volume mount",
      ],
      [
        `unable to open database file ${SECRET}`,
        "could not read the browser's cookie database (wrong profile dir, or it is locked)",
      ],
      [
        `Failed to decrypt with DPAPI keyring ${SECRET}`,
        "could not decrypt the browser cookies (the sidecar's keyring is unavailable)",
      ],
      // Nothing recognized: fall back to the shared classifier's ENUM KIND, never its message.
      [`boom ${SECRET}`, "unknown"],
    ];
    for (const [stderr, reason] of cases) {
      const { svc, applyCookies } = await make({
        browserProfile: profile,
        run: vi.fn(async (): Promise<YtDlpRun> => okRun({ stderr, code: 1 })),
      });
      const res = await svc.importFromBrowser();
      expect(res).toEqual({ ok: false, reason });
      expect(res.reason).not.toContain(SECRET);
      expect(applyCookies).not.toHaveBeenCalled();
    }
  });

  it("survives a yt-dlp that is not installed / times out", async () => {
    const profile = await profileWithDb();
    const { svc } = await make({
      browserProfile: profile,
      run: vi.fn(async (): Promise<YtDlpRun> => {
        throw new YtError(YtErrorKind.Timeout, `yt-dlp timed out reading ${SECRET}`);
      }),
    });
    const res = await svc.importFromBrowser();
    expect(res).toEqual({ ok: false, reason: "yt-dlp timed out" });
    expect(res.reason).not.toContain(SECRET);
  });
});

describe("CookieService security: a cookie value never leaves the module", () => {
  /** Every string the caller can see, from every method, concatenated for one blunt assertion. */
  async function everythingTheCallerSees(svc: CookieService): Promise<string> {
    const parts = [
      JSON.stringify(svc.health()),
      JSON.stringify(await svc.test()),
      JSON.stringify(await svc.saveFromText(NETSCAPE_EXPORT)),
      JSON.stringify(await svc.saveFromText(HEADER_PASTE)),
      JSON.stringify(await svc.saveFromText(`garbage paste holding ${SECRET}`)),
      JSON.stringify(await svc.importFromBrowser()),
      JSON.stringify(svc.health()),
    ];
    return parts.join("\n");
  }

  it("leaks nothing through a HEALTHY console", async () => {
    const { svc } = await make();
    const out = await everythingTheCallerSees(svc);
    expect(out).not.toContain(SECRET);
    expect(out).not.toContain(SECRET2);
  });

  it("leaks nothing when yt-dlp fails with our own cookies quoted in its stderr", async () => {
    // The realistic nightmare: yt-dlp echoes the cookie file it choked on, or a Set-Cookie from
    // the response, into stderr — and classifyYtdlpError puts a 500-char slice of that in
    // err.message. Nothing may forward it.
    const profile = await profileWithDb();
    const resolve = vi.fn(async (): Promise<TrackMeta> => {
      throw new YtError(YtErrorKind.Unknown, `yt-dlp failed (exit 1): cookie SID=${SECRET}`);
    });
    const { svc } = await make({
      browserProfile: profile,
      youtube: { resolve },
      run: vi.fn(async (): Promise<YtDlpRun> => okRun({ stderr: `SID=${SECRET}`, code: 1 })),
    });

    const out = await everythingTheCallerSees(svc);

    expect(out).not.toContain(SECRET);
    expect(out).not.toContain(SECRET2);
    // …and the failures really did happen (the assertion above is not vacuous).
    expect(out).toContain('"ok":false');
  });

  it("leaks nothing when the disk refuses the write", async () => {
    const cacheDir = await tmp();
    const notADir = join(cacheDir, "wall");
    await writeFile(notADir, "");
    const { svc } = await make({
      cacheDir: join(notADir, "cache"),
      jarPath: join(notADir, "cache", COOKIE_JAR_FILE),
    });

    const out = await everythingTheCallerSees(svc);

    expect(out).not.toContain(SECRET);
    expect(out).not.toContain(SECRET2);
  });

  it("keeps the jar itself off every surface: only the FILE holds the values", async () => {
    const { svc, jarPath } = await make();
    await svc.saveFromText(NETSCAPE_EXPORT);
    // The one and only place a cookie value is allowed to exist.
    expect(await readFile(jarPath, "utf8")).toContain(SECRET);
    // health() after the fact still says nothing about content — just booleans and stamps.
    const h = svc.health();
    expect(JSON.stringify(h)).not.toContain(SECRET);
    expect(Object.keys(h).sort()).toEqual([
      "browserProfileAvailable",
      "configured",
      "lastCheck",
      "source",
      "updatedAt",
    ]);
  });
});

// Both audits independently flagged this one: a jar the console wrote was silently ignored after a
// restart, because materializeCookies only returns a path when YT_COOKIES / YT_COOKIES_TEXT is set.
// The console exists precisely so an operator does NOT have to touch compose, so the jar — not the
// env var — is the artefact that must survive. src/index.ts now adopts an existing jar; this pins
// the contract the two sides agree on: defaultJarPath is where the console writes and boot looks.
describe("the console's jar is the thing that persists", () => {
  it("saveFromText writes exactly the jar path boot adopts (defaultJarPath)", async () => {
    const cacheDir = await tmp();
    const jarPath = defaultJarPath(cacheDir);
    const { svc } = await make({ cacheDir, jarPath });
    await svc.saveFromText(NETSCAPE_EXPORT);
    // The file boot will look for after a restart, with no env var set anywhere.
    expect(existsSync(defaultJarPath(cacheDir))).toBe(true);
    expect(await readFile(defaultJarPath(cacheDir), "utf8")).toContain(".youtube.com");
  });
});

// A Netscape entry is EXACTLY 7 tab-separated fields. Counting ">= 7" let a mangled paste (an extra
// tab, a copied table) pass validation, so the console reported "saved" for a jar yt-dlp then
// refuses to parse — the operator is told it worked and the bot stays silent.
describe("cookie line validation is exact", () => {
  it("rejects a paste whose lines carry MORE than 7 tab-separated fields", async () => {
    const cacheDir = await tmp();
    const { svc, applyCookies } = await make({ cacheDir, jarPath: defaultJarPath(cacheDir) });
    const mangled =
      "# Netscape HTTP Cookie File\n.youtube.com\tTRUE\t/\tTRUE\t2000000000\tSID\tv\tEXTRA\n";
    const res = await svc.saveFromText(mangled);
    expect(res.ok).toBe(false);
    expect(res.reason).toBe("no cookies found in that text");
    expect(applyCookies).not.toHaveBeenCalled(); // and nothing was applied to the live station
  });
});

// The pure half of the sign-in check. A jar is a SESSION only if it carries one of Google's auth
// cookies, for a Google domain, WITH a value — everything else is consent and preference noise.
describe("hasAuthCookie", () => {
  it("is true for any AUTH_COOKIE_NAMES entry on a google/youtube domain with a value", () => {
    expect(hasAuthCookie(SIGNED_IN_JAR)).toBe(true);
    expect(hasAuthCookie(NETSCAPE_EXPORT)).toBe(true);
    for (const name of AUTH_COOKIE_NAMES) {
      expect(hasAuthCookie(`.google.com\tTRUE\t/\tTRUE\t2000000000\t${name}\tv\n`), name).toBe(
        true,
      );
    }
    // The `#HttpOnly_` form is where the ones that matter actually live.
    expect(hasAuthCookie("#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t2000000000\tSID\tv\n")).toBe(true);
  });

  it("is false for the anonymous jar — eight cookies, not one of them a session", () => {
    // Not vacuous, and the whole defect in one line: the guard this replaces asked whether the
    // staged file had any cookie lines in it, and the answer was always yes.
    expect(countCookieLines(ANONYMOUS_JAR)).toBe(8);
    expect(hasAuthCookie(ANONYMOUS_JAR)).toBe(false);
  });

  it("is false when the value is EMPTY, however well-formed the line is", () => {
    expect(countCookieLines(EMPTY_AUTH_JAR)).toBe(9);
    expect(hasAuthCookie(EMPTY_AUTH_JAR)).toBe(false);
  });

  it("is false for an auth cookie NAME on somebody else's domain", () => {
    expect(hasAuthCookie(".evil.example\tTRUE\t/\tTRUE\t2000000000\tSID\tvalue\n")).toBe(false);
    expect(hasAuthCookie("notyoutube.com\tTRUE\t/\tTRUE\t2000000000\tSID\tvalue\n")).toBe(false);
  });

  it("tolerates CRLF, so a stray \\r never passes for a value", () => {
    expect(hasAuthCookie(".youtube.com\tTRUE\t/\tTRUE\t2000000000\tSID\t\r\n")).toBe(false);
    expect(hasAuthCookie(".youtube.com\tTRUE\t/\tTRUE\t2000000000\tSID\tv\r\n")).toBe(true);
  });
});

